-- The team index: every provider's code for an NFL team, and for its fantasy defense, points at one Omen team.
-- Verified 2026-10-16 against live leagues: Sleeper names a defense by its abbreviation (PHI, LAR); ESPN by
-- -16000 minus its team number (Chiefs D/ST -16012, team 12); Yahoo by 100000 plus the same team number
-- (Ravens 100033, team 33). ESPN and Yahoo share one team numbering. nflverse spells the Rams LA, Sleeper LAR.
-- Teams do not change ids when they relocate: Omen keeps one id per franchise as it plays today.

create table football.team_ids (
  provider     text not null check (provider in ('nflverse', 'sleeper', 'espn', 'yahoo')),
  provider_id  text not null check (provider_id ~ '^-?[A-Za-z0-9]{1,12}$'),
  kind         text not null check (kind in ('team', 'defense')),
  team_id      text not null references football.football_teams(team_id) on delete restrict,
  primary key (provider, provider_id, kind),
  unique (provider, kind, team_id)
);
comment on table football.team_ids is
  '[identity] The team index: each provider''s code for an NFL team and for its fantasy defense, pointing at one Omen team.';

