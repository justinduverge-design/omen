/**
 * Filter helpers — used by TradeAnalyzer autocomplete
 *
 * @param {string} position — matches NFL_PLAYERS[n].position
 * @param {string} query    — partial player name (case-insensitive)
 * @returns {Array}
 */
export function searchPlayers(position, query) {
  const needle = query.trim().toLowerCase();
  return NFL_PLAYERS.filter((p) => {
    const posMatch = !position || p.position === position;
    const nameMatch = !needle || p.name.toLowerCase().includes(needle);
    return posMatch && nameMatch;
  });
}
